#!/usr/bin/env python3

import argparse
import os
import sys
from pathlib import Path

import torch
import torch.nn.functional as F

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from datasets import Dataset
from kd import KD_RL

STRATEGY_NAMES = [
    "Structural",
    "Image",
    "Description",
    "Structural+Image",
    "Structural+Description",
    "Image+Description",
    "All three",
]


def ce_per_query(logits, truth):
    return F.cross_entropy(logits, truth, reduction="none")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--dataset", default="FB15K-237")
    parser.add_argument("--queries", type=int, default=1024)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--seed", type=int, default=2022)
    args = parser.parse_args()

    ckpt = args.checkpoint.expanduser().resolve()
    if not ckpt.is_file():
        raise FileNotFoundError(ckpt)

    torch.manual_seed(args.seed)
    os.chdir(ROOT / "src")

    dataset = Dataset(args.dataset)

    # Only load checkpoints generated by this trusted project.
    model = torch.load(
        ckpt,
        map_location="cuda",
        weights_only=False,
    )

    if not isinstance(model, KD_RL):
        raise TypeError(f"Expected KD_RL, got {type(model)}")

    model.eval()
    model.requires_grad_(False)

    strategies = model.strategy.to("cuda")

    if tuple(strategies.shape) != (7, 3):
        raise ValueError("Expected 7 strategies over 3 modalities")

    queries = torch.from_numpy(dataset.get_valid().astype("int64"))

    # Reproduce Experiment F's query sampling.
    if 0 < args.queries < len(queries):
        indices = torch.randperm(len(queries))[: args.queries]
        queries = queries[indices]

    total = 0
    positive = torch.zeros(7, dtype=torch.long)
    negative = torch.zeros(7, dtype=torch.long)
    advantage_pos = torch.zeros(7, dtype=torch.long)
    advantage_neg = torch.zeros(7, dtype=torch.long)
    advantage_zero = torch.zeros(7, dtype=torch.long)

    ce_sum = torch.zeros(7, dtype=torch.float64)
    policy_counts = torch.zeros(7, dtype=torch.long)
    oracle_counts = torch.zeros(7, dtype=torch.long)

    baseline_positive = 0
    chosen_positive = 0
    chosen_nonzero_adv = 0
    chosen_negative_adv = 0
    oracle_positive = 0

    all_same_reward = 0
    multiple_positive = 0
    all_positive = 0
    positive_ce_gap_sum = 0.0
    positive_ce_gap_n = 0

    policy_reward_below_best = 0

    for start in range(0, len(queries), args.batch_size):
        batch = queries[start : start + args.batch_size].cuda()
        truth = batch[:, 2]
        n = len(batch)

        with torch.no_grad():
            student_logits, _ = model.student(batch)
            teacher_outputs = model.teacher.forward(batch)

            preds_stack = torch.stack(
                [
                    teacher_outputs[0],
                    teacher_outputs[2],
                    teacher_outputs[4],
                ],
                dim=-1,
            )

            probs = model.rewarder(preds_stack)
            chosen = probs.argmax(dim=-1)

            # [batch, strategies, entities]
            candidate_logits = torch.einsum(
                "bem,sm->bse",
                preds_stack,
                strategies,
            )

            candidate_ce = torch.logsumexp(
                candidate_logits, dim=-1
            ) - candidate_logits.gather(
                2,
                truth[:, None, None].expand(-1, 7, 1),
            ).squeeze(-1)

            student_ce = ce_per_query(student_logits, truth)

            baseline_logits = preds_stack.mean(dim=-1)
            baseline_ce = ce_per_query(baseline_logits, truth)

            # Exact reward rule from KD_RL.forward_train().
            rewards = torch.where(
                candidate_ce < student_ce[:, None],
                1.0,
                -10.0,
            )

            baseline_reward = torch.where(
                baseline_ce < student_ce,
                1.0,
                -10.0,
            )

            advantages = rewards - baseline_reward[:, None]

            oracle_ce, oracle = candidate_ce.min(dim=1)

            chosen_reward = rewards.gather(1, chosen[:, None]).squeeze(1)

            chosen_advantage = advantages.gather(1, chosen[:, None]).squeeze(1)

            best_reward = rewards.max(dim=1).values

            num_positive = (rewards == 1).sum(dim=1)

            # CE spread only among positively rewarded strategies.
            positive_ce = candidate_ce.masked_fill(rewards != 1, float("inf"))
            worst_positive_ce = candidate_ce.masked_fill(rewards != 1, float("-inf"))

            positive_gap = (
                worst_positive_ce.max(dim=1).values - positive_ce.min(dim=1).values
            )

            valid_gap = num_positive >= 2

            positive_ce_gap_sum += positive_gap[valid_gap].sum().item()
            positive_ce_gap_n += valid_gap.sum().item()

            total += n

            positive += (rewards == 1).sum(dim=0).cpu()
            negative += (rewards == -10).sum(dim=0).cpu()

            advantage_pos += (advantages > 0).sum(dim=0).cpu()
            advantage_neg += (advantages < 0).sum(dim=0).cpu()
            advantage_zero += (advantages == 0).sum(dim=0).cpu()

            ce_sum += candidate_ce.sum(dim=0).double().cpu()

            policy_counts += torch.bincount(chosen.cpu(), minlength=7)
            oracle_counts += torch.bincount(oracle.cpu(), minlength=7)

            baseline_positive += (baseline_reward == 1).sum().item()

            chosen_positive += (chosen_reward == 1).sum().item()

            chosen_nonzero_adv += (chosen_advantage != 0).sum().item()

            chosen_negative_adv += (chosen_advantage < 0).sum().item()

            oracle_positive += (oracle_ce < student_ce).sum().item()

            all_same_reward += ((num_positive == 0) | (num_positive == 7)).sum().item()

            multiple_positive += valid_gap.sum().item()
            all_positive += (num_positive == 7).sum().item()

            policy_reward_below_best += (chosen_reward < best_reward).sum().item()

    def pct(count):
        return 100.0 * count / total

    print("\n===== EXPERIMENT G: REWARD SIGNAL AUDIT =====")
    print(f"Checkpoint: {ckpt}")
    print(f"Validation queries: {total}")
    print("Policy decision: argmax (deterministic audit)")
    print("Reward: +1 if teacher CE < student CE, else -10")
    print("Advantage: strategy reward - mean-teacher reward")

    print("\n===== REWARD BY STRATEGY =====")
    print(
        f"{'ID':<3} {'Strategy':<25} "
        f"{'CE':>9} {'R+ %':>9} "
        f"{'A+ %':>9} {'A- %':>9} {'A0 %':>9}"
    )

    for i, name in enumerate(STRATEGY_NAMES):
        print(
            f"{i:<3} {name:<25} "
            f"{ce_sum[i].item() / total:9.4f} "
            f"{pct(positive[i].item()):9.2f} "
            f"{pct(advantage_pos[i].item()):9.2f} "
            f"{pct(advantage_neg[i].item()):9.2f} "
            f"{pct(advantage_zero[i].item()):9.2f}"
        )

    print("\n===== BASELINE AND POLICY =====")
    print(f"Baseline positive reward: {pct(baseline_positive):.2f}%")
    print(f"Policy positive reward:   {pct(chosen_positive):.2f}%")
    print(f"Oracle positive reward:   {pct(oracle_positive):.2f}%")
    print(f"Policy nonzero advantage: {pct(chosen_nonzero_adv):.2f}%")
    print(f"Policy negative advantage:{pct(chosen_negative_adv):.2f}%")
    print(
        "Policy reward worse than best available reward: "
        f"{pct(policy_reward_below_best):.2f}%"
    )

    print("\n===== REWARD DISCRIMINATION =====")
    print(f"All seven strategies have identical reward: {pct(all_same_reward):.2f}%")
    print(f"At least two strategies have reward +1: {pct(multiple_positive):.2f}%")
    print(f"All seven strategies have reward +1: {pct(all_positive):.2f}%")
    if positive_ce_gap_n:
        print(
            "Mean CE gap among positively rewarded strategies: "
            f"{positive_ce_gap_sum / positive_ce_gap_n:.6f}"
        )

    print("\n===== POLICY VS CE ORACLE =====")
    for i, name in enumerate(STRATEGY_NAMES):
        print(
            f"{i} {name:<25} "
            f"policy={pct(policy_counts[i].item()):6.2f}% "
            f"oracle={pct(oracle_counts[i].item()):6.2f}%"
        )

    print("============================================")


if __name__ == "__main__":
    main()
